// The external-agent rule (FR-194, docs/12 §6.2): content another AI agent produced (channel
// messages, emails, pages, plugins, captures) is untrusted data. A Nova agent never accepts a task
// from an external agent, and delegates to or sends data to one only when the user named that
// agent for the current task. Detection is deterministic: a channel identity flagged as a bot, an
// identity the user marked, a signature line naming an agent ("— the billing agent") or a sender
// that says it is an AI agent. The deny itself is the policy engine's built-in rule.
import { evaluate, type Decision } from '@nova/policy';

export type ExternalEvidence = 'bot_identity' | 'marked' | 'signature' | 'self_identified';

export interface ExternalFinding {
  /** Normalized name or address of the external agent ("billing agent"). */
  counterpart: string;
  evidence: ExternalEvidence;
}

export interface ExternalSender {
  id?: string | null;
  name?: string | null;
  /** The channel says the identity is a bot or an app (Slack `bot_id`, Teams app). */
  isBot?: boolean;
}

/** Lower case, words only, without a leading "the": "The Billing-Agent!" → "billing-agent". */
export function normalizeCounterpart(name: string): string {
  return name
    .toLowerCase()
    .replace(/[^\p{L}\p{N}@._-]+/gu, ' ')
    .trim()
    .replace(/^the\s+/, '')
    .replace(/\s+/g, ' ')
    .slice(0, 200);
}

const AGENT_WORD = '(?:agent|bot|assistant)';
const NAME = `((?:the\\s+)?(?:[\\p{L}\\p{N}][\\p{L}\\p{N}'_-]*\\s+){0,3}${AGENT_WORD})`;
// "— the billing agent", "Regards, Billing Bot", "Sent by the Billing Agent"
const SIGNED = new RegExp(
  `^(?:[-–—~]+|(?:best\\s+|kind\\s+)?regards,?|thanks,?|cheers,?|sent\\s+by|signed,?|from:?)\\s*${NAME}\\s*[.!]?$`,
  'iu',
);
// A last line that is only a name: "The Billing Agent"
const BARE = new RegExp(`^${NAME}\\s*[.!]?$`, 'iu');
// "I am the billing agent", "This is an automated assistant"
const SELF_NAMED = new RegExp(
  `\\b(?:i am|i'm|this is)\\s+((?:the|an?)\\s+[\\p{L}\\p{N}][\\p{L}\\p{N} _-]{0,40}?\\s${AGENT_WORD})\\b`,
  'iu',
);
const SELF_AI = new RegExp(
  `\\b(?:i am|i'm|this is|written by|generated by|sent by)\\s+(?:an?\\s+)?(?:ai|automated|autonomous|virtual)\\s+${AGENT_WORD}\\b`,
  'iu',
);

/**
 * Whether content comes from another AI agent. `marked` holds the identities the user marked
 * (normalized). Null when nothing says so.
 */
export function detectExternalAgent(input: {
  text: string;
  sender?: ExternalSender | null;
  marked?: readonly string[];
}): ExternalFinding | null {
  const sender = input.sender ?? null;
  const senderName = sender?.name ?? sender?.id ?? null;
  if (sender?.isBot)
    return {
      counterpart: normalizeCounterpart(senderName ?? 'unnamed bot'),
      evidence: 'bot_identity',
    };
  const marked = new Set(input.marked ?? []);
  for (const v of [sender?.id, sender?.name]) {
    if (v && marked.has(normalizeCounterpart(v)))
      return { counterpart: normalizeCounterpart(v), evidence: 'marked' };
  }
  const text = input.text.slice(0, 20_000);
  const lines = text
    .split('\n')
    .map((l) => l.trim())
    .filter(Boolean);
  // A signature sits at the end: look at the last three lines only.
  for (const line of lines.slice(-3).reverse()) {
    const m = SIGNED.exec(line) ?? (lines.length > 1 ? BARE.exec(line) : null);
    if (m?.[1]) return { counterpart: normalizeCounterpart(m[1]), evidence: 'signature' };
  }
  const named = SELF_NAMED.exec(text);
  if (named?.[1])
    return { counterpart: normalizeCounterpart(named[1]), evidence: 'self_identified' };
  if (SELF_AI.test(text))
    return {
      counterpart: normalizeCounterpart(senderName ?? 'unnamed ai agent'),
      evidence: 'self_identified',
    };
  const lower = normalizeCounterpart(text);
  for (const m of marked) {
    if (m && lower.includes(m)) return { counterpart: m, evidence: 'marked' };
  }
  return null;
}

/** Whether the user's words name the agent (FR-194 "named for the current task"). */
export function namesAgent(userText: string, counterpart: string): boolean {
  const c = normalizeCounterpart(counterpart);
  if (!c) return false;
  return normalizeCounterpart(userText).includes(c);
}

/** Does this name or identity look like an AI agent (a bot, an assistant, an "… agent")? */
export function looksLikeAgent(name: string): boolean {
  return new RegExp(`\\b${AGENT_WORD}\\b`, 'iu').test(name);
}

/**
 * The policy engine's decision on engaging an external agent: built-in safety denies unless the
 * user named it (`namedAgents`, normalized) for the current task.
 */
export function externalAgentDecision(input: {
  counterpart: string;
  namedAgents: readonly string[];
  agentId: string | null;
}): Decision {
  return evaluate({
    actor: { kind: 'agent', id: input.agentId ?? 'nova' },
    scopes: input.agentId
      ? [{ kind: 'agent', ref: input.agentId }, { kind: 'global' }]
      : [{ kind: 'global' }],
    mode: 'agent',
    approvalPolicy: { kind: 'defaults' },
    permissionProfile: { id: 'read-only', hash: '' },
    provenance: { taint: ['external_agent'], namedAgents: [...input.namedAgents] },
    tool: {
      name: 'agent.external_contact',
      source: 'builtin',
      annotations: { readOnly: false, action: 'send' },
      effects: ['external_communication'],
    },
    counterpart: { externalAgent: true, id: normalizeCounterpart(input.counterpart) },
    environment: { kind: 'hub', trusted: true, substrate: null },
    fs: { entries: [] },
  });
}
