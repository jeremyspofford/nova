// Every Hub route, classified (ADR-097 D7; closes R-032). Each route the fully wired Hub registers
// is listed exactly once, by method and Fastify pattern, under the class of caller it is for:
//   public  no session: open, or a credential of its own (a setup code, an invitation, a signed
//           link, a sender's signature; contracts/hub-api.md §1)
//   owner   the Hub's own administration and machine: a member is refused (`owner_only`)
//   member  any signed-in person of the Hub, on their own account's data
//   device  a device's own credential (novad's, a pairing code or device key, a PXE boot token)
//   node    a compute node's credential
//   app     a client token of its own (Nova's MCP server, FR-044; third-party apps, FR-222)
// The web shell's files are listed too (WEB_SHELL_ROUTES; `/assets/*` stands for the built files
// under it). The member guard (access.ts) refuses a non-owner every `owner` route and every route
// that is not listed, wherever it is (fail closed); apps/hub/test/routes.test.ts fails for a route
// that is not listed, one listed twice, or one that no longer exists. Member routes an app token
// may also reach are the appauth area's list (APP_ROUTE_SCOPES), which may only name member
// routes.

export const ROUTE_CLASSES = ['public', 'owner', 'member', 'device', 'node', 'app'] as const;
export type RouteClass = (typeof ROUTE_CLASSES)[number];

export interface RouteGroup {
  class: RouteClass;
  /**
   * Owner groups: what a member is refused ("only the owner of this Hub can change ..."). Other
   * groups: how the routes authenticate or whose data they serve.
   */
  why: string;
  /** `METHOD /pattern`, exactly as the Hub registers it (HEAD is GET's). */
  routes: readonly string[];
}

