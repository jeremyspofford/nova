/**
 * The web shell (apps/web/dist): the page, its service worker, manifest and icons, and the built
 * files under `/assets/` (their names carry content hashes, so the entry ends in `/*`). They are
 * public: the page needs no session, and everything it shows comes from the API. A file added to
 * the web app's root must join this list, or members are refused it and routes.test.ts fails.
 */
export const WEB_SHELL_ROUTES: readonly string[] = [
  'GET /',
  'GET /index.html',
  'GET /sw.js',
  'GET /manifest.webmanifest',
  'GET /icon.svg',
  'GET /icon-maskable.svg',
  'GET /assets/*',
];
const WEB_SHELL_WHY = "the web shell's files";
const WEB_EXACT = new Set(WEB_SHELL_ROUTES.filter((r) => !r.endsWith('/*')));
const WEB_PREFIXES = WEB_SHELL_ROUTES.filter((r) => r.endsWith('/*')).map((r) => r.slice(0, -1));

function key(method: string, route: string): string {
  const m = method.toUpperCase();
  return `${m === 'HEAD' ? 'GET' : m} ${route}`;
}

/** A web shell file: listed exactly, or a plain file path under a listed folder (no parameters). */
function webShell(k: string): boolean {
  if (WEB_EXACT.has(k)) return true;
  return WEB_PREFIXES.some(
    (p) => k.startsWith(p) && k.length > p.length && !/[:*]/.test(k.slice(p.length)),
  );
}

/**
 * The class of a route (`route` is the matched Fastify pattern, never the raw URL); null for a
 * route nobody listed, wherever it is.
 */
export function routeClass(method: string, route: string | undefined): RouteClass | null {
  if (!route) return null;
  return routeEntry(method, route)?.class ?? null;
}

/** The listed classification of a route with its group's `why`; null when it is not listed. */
export function routeEntry(
  method: string,
  route: string,
): { class: RouteClass; why: string } | null {
  const k = key(method, route);
  const hit = BY_ROUTE.get(k);
  if (hit) return hit;
  return webShell(k) ? { class: 'public', why: WEB_SHELL_WHY } : null;
}
