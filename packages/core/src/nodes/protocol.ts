// Hub ↔ compute node wire shapes for /node/v1 (contracts/hub-api.md §2, §7; FR-126). The node
// side (services/compute) sends exactly these bodies; the Hub validates them here.
import { z } from 'zod';
import { NovaError } from '@nova/shared';
import { PUBLIC_KEY_PATTERN, SIGNATURE_PATTERN } from './crypto.ts';

/** Node protocol versions this Hub speaks (hub-api §7: the highest common one is used). */
export const NODE_PROTOCOL_VERSIONS: readonly number[] = [1];

/** Default heartbeat period; three missed beats mark a node unreachable (ADR-089). */
export const HEARTBEAT_INTERVAL_MS = 10_000;
export const MISSED_BEATS = 3;
/** Enrollment tokens are one use and live 15 minutes. */
export const ENROLL_TOKEN_TTL_MS = 15 * 60 * 1000;
export const ENROLL_TOKEN_PREFIX = 'nve_';
export const NODE_CREDENTIAL_PREFIX = 'nvn_';

const endpointSchema = z
  .url({ protocol: /^https?$/ })
  .max(500)
  .refine((u) => {
    const url = new URL(u);
    return !url.username && !url.password && !url.search && !url.hash;
  }, 'the endpoint must be a plain http(s) base URL');

export const capabilityDocumentSchema = z.record(z.string(), z.unknown());

export const registerNodeSchema = z.object({
  enrollToken: z.string().min(10).max(200),
  name: z.string().trim().min(1).max(100),
  endpoint: endpointSchema,
  publicKey: z.string().regex(PUBLIC_KEY_PATTERN, 'a raw Ed25519 public key, base64url'),
  capability: capabilityDocumentSchema,
  signature: z.string().regex(SIGNATURE_PATTERN, 'an Ed25519 signature, base64url'),
  /** Generated by the node; the Hub keeps it in the vault to call the node's job API. */
  jobToken: z.string().min(32).max(200),
  protocolVersions: z.array(z.number().int().min(1).max(1000)).min(1).max(16),
});
export type RegisterNodeRequest = z.infer<typeof registerNodeSchema>;

export interface RegisterNodeResponse {
  nodeId: string;
  /** `nvn_…`, returned once; the Hub stores only its hash. */
  credential: string;
  heartbeatIntervalMs: number;
  protocolVersion: number;
}

export const nodeLoadSchema = z.object({
  running: z.number().int().min(0).max(100_000),
  queued: z.number().int().min(0).max(100_000),
});

export const heartbeatSchema = z.object({
  load: nodeLoadSchema,
  /** The backend's current model ids (unsigned: it can hide a model, never add one). */
  models: z.array(z.string().min(1).max(300)).max(2_000).optional(),
});
export type HeartbeatRequest = z.infer<typeof heartbeatSchema>;

export const syncModelsSchema = z.object({
  capability: capabilityDocumentSchema,
  signature: z.string().regex(SIGNATURE_PATTERN, 'an Ed25519 signature, base64url'),
});
export type SyncModelsRequest = z.infer<typeof syncModelsSchema>;

/** The highest version both sides speak; `capability_missing` naming both lists otherwise. */
export function negotiateProtocol(offered: readonly number[]): number {
  const common = offered.filter((v) => NODE_PROTOCOL_VERSIONS.includes(v));
  if (common.length === 0) {
    throw new NovaError('capability_missing', 'no node protocol version in common', {
      details: { hub: [...NODE_PROTOCOL_VERSIONS], node: [...offered] },
    });
  }
  return Math.max(...common);
}
