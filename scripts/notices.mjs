// Third-party license check and notices (AGENTS.md §11, docs/19 §3).
// Walks the production dependency tree, fails on licenses not allowed in the default build, and
// writes build/THIRD_PARTY_NOTICES.md. Usage: node scripts/notices.mjs [--check]
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const ALLOWED = new Set([
  'MIT',
  'MIT-0',
  'Apache-2.0',
  'BSD-2-Clause',
  'BSD-3-Clause',
  '0BSD',
  'ISC',
  'MPL-2.0',
  'CC0-1.0',
  'Unlicense',
  'BlueOak-1.0.0',
  'Python-2.0',
  'CC-BY-4.0',
  'Zlib',
]);
// Our own workspaces carry the app license (ADR-022); they are not third-party.
const isOwn = (name) => name === 'nova' || name.startsWith('@nova/');

const tree = JSON.parse(
  execFileSync('npm', ['ls', '--omit=dev', '--all', '--json', '--long'], {
    cwd: root,
    maxBuffer: 64 * 1024 * 1024,
  }).toString(),
);

const seen = new Map();
(function walk(node) {
  for (const [name, dep] of Object.entries(node.dependencies ?? {})) {
    if (!dep.path || seen.has(`${name}@${dep.version}`)) continue;
    if (!isOwn(name))
      seen.set(`${name}@${dep.version}`, { name, version: dep.version, path: dep.path });
    walk(dep);
  }
})(tree);

const problems = [];
const rows = [];
for (const { name, version, path } of [...seen.values()].sort((a, b) =>
  a.name.localeCompare(b.name),
)) {
  const pkg = JSON.parse(readFileSync(join(path, 'package.json'), 'utf8'));
  const raw =
    typeof pkg.license === 'string'
      ? pkg.license
      : (pkg.license?.type ?? (pkg.licenses ?? []).map((l) => l.type).join(' OR '));
  const license = raw || 'UNKNOWN';
  const options = license.replace(/[()]/g, '').split(/\s+OR\s+/);
  if (!options.some((l) => ALLOWED.has(l.trim()))) problems.push(`${name}@${version}: ${license}`);
  const file = readdirSync(path).find((f) => /^(licen[cs]e|copying)(\.|$)/i.test(f));
  rows.push({
    name,
    version,
    license,
    text: file ? readFileSync(join(path, file), 'utf8').trim() : '',
  });
}

if (problems.length) {
  console.error(
    `notices: ${problems.length} dependency license(s) not allowed in the default build:`,
  );
  for (const p of problems) console.error(`  - ${p}`);
  process.exit(1);
}

if (!process.argv.includes('--check')) {
  const out = join(root, 'build');
  if (!existsSync(out)) mkdirSync(out, { recursive: true });
  const body = [
    '# Third-party notices',
    '',
    'Nova includes the following third-party software. Generated by `scripts/notices.mjs`.',
    '',
    ...rows.flatMap((r) => [
      `## ${r.name} ${r.version} (${r.license})`,
      '',
      r.text ? '```\n' + r.text + '\n```' : '_No license file shipped._',
      '',
    ]),
  ].join('\n');
  writeFileSync(join(out, 'THIRD_PARTY_NOTICES.md'), body);
}
console.log(`notices: ok (${rows.length} production dependencies, all permissively licensed)`);
