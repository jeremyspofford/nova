#!/usr/bin/env node
// Root CLAUDE.md and AGENTS.md (owner queue A3, docs/plans/owner-priority-queue-2026-11-02.md):
// generated pointers into the builder packet (docs/builder-packet/) and the other canonical docs,
// never copies of their content. An agent that opens the repo finds where to start; the rules
// themselves stay in one place, the packet.
//
//   node scripts/agent-pointers.js           write CLAUDE.md and AGENTS.md
//   node scripts/agent-pointers.js --check   fail if either isn't what this script makes
//
// Deterministic: the same packet and package.json always make the same files (no clock, no git).
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

export const ROOT = join(import.meta.dirname, '..');
export const TARGETS = ['CLAUDE.md', 'AGENTS.md'];

// What to read first, in order: [path from the repo root, what it is for].
export const READ_FIRST = [
  ['docs/builder-packet/START-HERE.md', 'the packet entry; follow its reading order'],
  ['docs/builder-packet/OPERATING-RULES.md', 'how a builder works'],
  ['docs/builder-packet/WORK-LEDGER-AND-VERIFICATION.md', 'durable work and evidence'],
  ['docs/builder-packet/ROADMAP-AND-GATES.md', 'build order and gates'],
  ['docs/plans/owner-priority-queue-2026-11-02.md', 'the owner priority queue'],
  ['docs/LEDGER.md', 'the ledger history'],
  ['docs/ledger/README.md', 'the per-merge ledger entry'],
  ['docs/changelog/README.md', 'the changelog fragment'],
];

// The gates: [command, npm script it needs or null, what it checks].
export const GATES = [
  ['npm run check', 'check', 'tokens, themes, typecheck and the test suite'],
  ['npm run test:ui', 'test:ui', 'the browser tests'],
  ['npm run changelog -- --check', 'changelog', 'CHANGELOG.md matches its fragments'],
  ['sh scripts/check-changelog.sh origin/main', null, 'a fragment and ledger entry where needed'],
  ['node scripts/agent-pointers.js --check', null, 'these files match their generator'],
];

// The one line saying what Nova is, taken from the packet entry rather than restated here.
export function whatNovaIs(root = ROOT) {
  const start = readFileSync(join(root, 'docs/builder-packet/START-HERE.md'), 'utf8');
  const m = start.match(/^You are building \*\*Nova\*\*, ([^.\n]+)\./m);
  if (!m) throw new Error('docs/builder-packet/START-HERE.md: no "You are building **Nova**, …." line to take Nova\'s one-line description from.');
  return `Nova is ${m[1]}.`;
}

export function generate(root = ROOT) {
  const scripts = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')).scripts ?? {};
  for (const [cmd, script] of GATES) if (script && !scripts[script]) throw new Error(`package.json has no "${script}" script for: ${cmd}`);
  for (const [path] of READ_FIRST) if (!existsSync(join(root, path))) throw new Error(`${path} doesn't exist.`);
  return [
    '<!-- Generated by scripts/agent-pointers.js. Do not edit by hand: change the script, then run node scripts/agent-pointers.js. -->',
    '',
    '# Nova: where to start',
    '',
    `${whatNovaIs(root)} (docs/builder-packet/START-HERE.md)`,
    '',
    'This file only points. The rules live in the documents below; where they and this file differ, they win.',
    '',
    '## Read first, in order',
    '',
    ...READ_FIRST.map(([path, what], i) => `${i + 1}. [${path}](${path}): ${what}`),
    '',
    '## Gates',
    '',
    ...GATES.map(([cmd, , what]) => `- \`${cmd}\`: ${what}`),
    '',
  ].join('\n');
}

// The targets whose committed text isn't what generate() makes.
export function stale(root = ROOT) {
  const text = generate(root);
  return TARGETS.filter((f) => !existsSync(join(root, f)) || readFileSync(join(root, f), 'utf8') !== text);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  if (process.argv.includes('--check')) {
    const out = stale();
    if (out.length) {
      console.log(`Out of date: ${out.join(', ')}. Run: node scripts/agent-pointers.js`);
      process.exit(1);
    }
    console.log(`${TARGETS.join(' and ')} match scripts/agent-pointers.js.`);
  } else {
    const text = generate();
    for (const f of TARGETS) writeFileSync(join(ROOT, f), text);
    console.log(`Wrote ${TARGETS.join(' and ')}.`);
  }
}
