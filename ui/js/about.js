// About Nova (/about), What's new (/changelog) and Where Nova stands (/pipeline): Settings' children
// (nav.js), reached from Settings › About Nova and from the version stamp at the rail's foot. Specs:
// docs/builder-packet/nova-versioning-changelog-2026-11-03.md and its 2026-11-06 delta; designs: the
// styleguide's ui-about compositions. The pieces are components.js's (aboutCard, changelogEntry,
// pipelineRow); this module reads the core and draws each view. app.js loads it the first time one
// of these views opens.
//
// Every read is the core's, read-only: GET /api/v1/version, /changelog and /pipeline. Nothing here is
// kept by hand: the changelog is CHANGELOG.md as the core reads it, the pipeline is generated by the
// core from the roadmap, gate evidence, plans and the ledger each time it opens.
import { request } from './core.js';
import { ICONS, PIPELINE_STATES, aboutCard, changelogEntry, emptyState, pipelineRow } from './components.js';
import { escapeHtml as esc } from './markdown.js';
import { waitingLine } from './wait.js';
import { setBuild } from './shell.js';

const HEAD = {
  about: ['About Nova', 'Which Nova this is, and whether it is the latest build.'],
  changelog: ['What’s new', 'Every change to Nova in plain words, newest first: the same list as the changelog file kept with Nova’s code.'],
  pipeline: ['Where Nova stands', 'What is merged, in progress, designed and not started, each with the record it stands on.'],
};

// Which read each view's last answer belongs to: an answer to a read the person has since left (or
// read again) is dropped, never drawn over the newer one.
const generation = { about: 0, changelog: 0, pipeline: 0 };

const head = (view) => {
  const [title, lede] = HEAD[view];
  const back = view === 'about' ? ['/settings#about', 'Settings'] : ['/about', 'About Nova'];
  return `<p class="view-crumb"><a class="link view-crumb-link" href="${back[0]}">${ICONS.back}<span>${back[1]}</span></a></p><header class="view-head"><h2 class="view-title">${title}</h2><p class="view-lede">${lede}</p></header>`;
};
const saved = (stale) => (stale ? '<p class="settings-note" role="status">Saved earlier, while Nova was out of reach: this may not be the latest.</p>' : '');
// A read that failed (F-023): said, with Try again, which reads it again without leaving the page.
const retry = (view) => `<div class="connection-actions"><button type="button" class="btn" data-about-retry="${view}">Try again</button></div>`;
const failed = (what, view) => `<div data-about-failed>${emptyState({ title: `Nova couldn’t read ${what}`, line: 'Its server didn’t answer.', action: retry(view) })}</div>`;

async function read(view, path) {
  const mine = ++generation[view];
  try {
    const r = await request('GET', path);
    return mine === generation[view] ? r : null;
  } catch (e) {
    if (mine !== generation[view]) return null;
    return { error: e };
  }
}

// ---- About Nova -------------------------------------------------------------------------------------

async function about(root) {
  root.innerHTML = `${head('about')}${aboutCard({ state: 'loading' })}`;
  const r = await read('about', '/version');
  if (!r) return;
  if (r.error) { root.innerHTML = `${head('about')}${aboutCard({ state: 'failed' })}${retry('about')}`; return; }
  // The stamp at the rail's foot says the same as this page, as of now.
  if (!r.stale) setBuild(r.data);
  root.innerHTML = `${head('about')}${saved(r.stale)}${aboutCard({ build: r.data })}`;
}

// ---- What's new ---------------------------------------------------------------------------------------

// The running version pinned on top, and any gap between it and the changelog said plainly: a
// changelog newer than the running version (the new code is checked out, Nova not yet restarted on
// it), and the changes merged since the newest version.
export function pin(log) {
  const run = log.running;
  const commit = run.commit_short ? ` <span class="about-mono">${esc(run.commit_short)}</span>` : '';
  const lines = [];
  if (log.newest && log.newest !== run.version) {
    lines.push(log.versions.some((v) => v.version === run.version)
      ? `The newest version in the changelog is ${esc(log.newest)}, newer than the one running: a redeploy is pending.`
      : `The changelog’s newest version is ${esc(log.newest)}; the version running, ${esc(run.version)}, has no entry of its own.`);
  } else if (log.newest) lines.push('This is the newest version in the changelog.');
  if (log.waiting.length) lines.push(`${log.waiting.length === 1 ? 'One change has' : `${log.waiting.length} changes have`} been merged since; ${log.waiting.length === 1 ? 'it comes' : 'they come'} with the next version.`);
  return `<section class="changelog-pin" aria-label="The version you’re running"><p class="changelog-kicker">You’re running</p><p class="changelog-running">Nova ${esc(run.version)}${commit}</p>${lines.map((l) => `<p class="changelog-gap">${l}</p>`).join('')}</section>`;
}

export function changelogPage(log) {
  const waiting = log.waiting.length ? changelogEntry({ waiting: true, sections: mergeSections(log.waiting) }) : '';
  const versions = log.versions.map((v) => changelogEntry({ ...v, running: v.version === log.running.version })).join('');
  const problems = log.problems.length ? `<details class="changelog-problems"><summary>${log.problems.length === 1 ? 'One entry' : `${log.problems.length} entries`} couldn’t be read and ${log.problems.length === 1 ? 'is' : 'are'} left out</summary><ul>${log.problems.map((p) => `<li>${esc(p)}</li>`).join('')}</ul></details>` : '';
  const body = waiting || versions ? `${waiting}${versions}` : emptyState({ title: 'No changes to show yet', line: 'Each change that alters what Nova does comes with a plain-language entry; they will appear here.' });
  return `${pin(log)}${problems}<div class="changelog-list">${body}</div>`;
}

// The waiting fragments, newest first, as one block: each section's items in fragment order.
function mergeSections(fragments) {
  const out = new Map();
  for (const f of fragments) for (const s of f.sections) out.set(s.name, [...(out.get(s.name) ?? []), ...s.items]);
  return ['Added', 'Changed', 'Removed', 'Fixed', 'Security'].filter((n) => out.has(n)).map((name) => ({ name, items: out.get(name) }));
}

async function changelog(root) {
  root.innerHTML = `${head('changelog')}<div data-waiting>${waitingLine('Reading the changelog', { key: 'view-changelog' })}</div>`;
  const r = await read('changelog', '/changelog');
  if (!r) return;
  root.innerHTML = `${head('changelog')}${r.error ? failed('the changelog', 'changelog') : `${saved(r.stale)}${changelogPage(r.data)}`}`;
}

// ---- Where Nova stands ------------------------------------------------------------------------------------

export function pipelinePage(p) {
  const tally = `<ul class="pipeline-tally" aria-label="Totals">${Object.entries(PIPELINE_STATES).map(([k, w]) => `<li class="pipeline-col" data-p="${k}"><span class="pipeline-mark" data-p="${k}" aria-hidden="true"></span><span class="pipeline-col-name">${w}</span><span class="pipeline-col-n">${p.counts[k] ?? 0}</span></li>`).join('')}</ul>`;
  const streams = p.workstreams.map((w, i) => {
    const merged = w.items.filter((x) => x.state === 'merged').length;
    return `<section class="pipeline-stream" aria-labelledby="ps-${i}"><h3 class="pipeline-stream-head"><span id="ps-${i}">${esc(w.name)}</span><span class="pipeline-stream-n">${merged} of ${w.items.length} merged</span></h3><ul class="pipeline-list">${w.items.map((it) => pipelineRow(it)).join('')}</ul></section>`;
  }).join('');
  const problems = p.problems.length ? `<details class="changelog-problems"><summary>${p.problems.length === 1 ? 'One record' : `${p.problems.length} records`} couldn’t be read and ${p.problems.length === 1 ? 'is' : 'are'} left out</summary><ul>${p.problems.map((x) => `<li>${esc(x)}</li>`).join('')}</ul></details>` : '';
  return `${tally}<p class="pipeline-note">Made just now from Nova’s own records: ${p.sources.map((s) => `<span class="about-mono">${esc(s)}</span>`).join(', ')}. Nothing here is kept by hand. Nova doesn’t see open pull requests, so “In progress” is only what the records show: a milestone with some of its phases merged, or a series not yet finished.</p>${problems}${streams || emptyState({ title: 'Nothing to show yet', line: 'The roadmap and the ledger aren’t in this build of Nova.' })}`;
}

async function pipeline(root) {
  root.innerHTML = `${head('pipeline')}<div data-waiting>${waitingLine('Reading the roadmap and the ledger', { key: 'view-pipeline' })}</div>`;
  const r = await read('pipeline', '/pipeline');
  if (!r) return;
  root.innerHTML = `${head('pipeline')}${r.error ? failed('where Nova stands', 'pipeline') : `${saved(r.stale)}${pipelinePage(r.data)}`}`;
}

const VIEWS = { about, changelog, pipeline };
// Draws one of the three views into its root, reading the core afresh. The stamp at the rail's foot
// is read again with it, so it never says less than these pages do.
export function show(view, root) {
  if (!root.dataset.retryBound) {
    root.dataset.retryBound = '1';
    root.addEventListener('click', (e) => {
      const b = e.target.closest('[data-about-retry]');
      if (b && Object.hasOwn(VIEWS, b.dataset.aboutRetry)) VIEWS[b.dataset.aboutRetry](root);
    });
  }
  if (view !== 'about') request('GET', '/version').then((r) => { if (!r.stale) setBuild(r.data); }).catch(() => {});
  return VIEWS[view](root);
}
